// Regenerates the USDA catalog seed. Run by hand, never at app start:
//   node scripts/usda-import.mjs            (uses USDA_API_KEY, else the public DEMO_KEY)
// Nutrition comes only from FoodData Central. Price and stock in usda-foods.json are samples.
// USDA has no allergen data, so every product stays allergens_verified = false (fail-closed).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const foods = JSON.parse(
  readFileSync(new URL("scripts/usda-foods.json", root)),
);
const key = process.env.USDA_API_KEY || "DEMO_KEY";
const url = new URL("https://api.nal.usda.gov/fdc/v1/foods");
url.searchParams.set("api_key", key);
url.searchParams.set("format", "abridged");
url.searchParams.set("fdcIds", foods.map((food) => food.fdcId).join(","));

const response = await fetch(url);
if (!response.ok)
  throw new Error(`USDA request failed: HTTP ${response.status}`);
const records = new Map((await response.json()).map((f) => [f.fdcId, f]));

const text = (value) => `'${String(value).replaceAll("'", "''")}'`;
const number = (value) => (value === undefined ? "NULL" : String(value));
const categories = {
  "ngu-coc": "Ngũ cốc",
  "cac-loai-hat": "Các loại hạt",
  "hat-dinh-duong": "Hạt dinh dưỡng",
  "cac-loai-dau": "Các loại đậu",
  "thuc-pham-khac": "Thực phẩm khác",
};
const lines = [
  "-- Generated by scripts/usda-import.mjs. Do not edit by hand.",
  "-- Nutrition: USDA FoodData Central (public domain), per 100 g of a generic food.",
  "-- Price and stock are samples. USDA has no allergen data, so allergens stay unverified.",
  ...Object.entries(categories).map(
    ([slug, name]) =>
      `INSERT INTO categories(name,slug) VALUES (${text(name)},${text(slug)}) ON CONFLICT (slug) DO NOTHING;`,
  ),
];
for (const food of foods) {
  const record = records.get(food.fdcId);
  // A wrong id must stop the import rather than attach numbers to the wrong product.
  if (!record?.description.includes(food.expect))
    throw new Error(
      `FDC ${food.fdcId}: expected "${food.expect}", got "${record?.description}"`,
    );
  const amount = (id) =>
    record.foodNutrients.find((n) => n.number === id)?.amount;
  const [kcal, protein, carbs, fat] = ["208", "203", "205", "204"].map(amount);
  const complete = [kcal, protein, carbs, fat].every((v) => v !== undefined);
  const description = `Dinh dưỡng theo USDA FoodData Central (${record.dataType}, FDC ${record.fdcId}: ${record.description}), tính trên 100 g thực phẩm chung, không phải nhãn của thương hiệu. Giá và tồn kho là dữ liệu mẫu.`;
  const name = text(food.name);
  lines.push(
    `INSERT INTO products(category_id,name,description,price,stock,serving_size,serving_unit,nutrition_complete,allergens_verified)
SELECT c.id,${name},${text(description)},${food.price},${food.stock},100,'g',${complete},false
FROM categories c WHERE c.slug=${text(food.category)}
AND NOT EXISTS (SELECT 1 FROM products p WHERE p.name=${name});`,
    `INSERT INTO product_nutrition(product_id,calories,protein_g,carbs_g,fat_g,sugar_g,fiber_g,sodium_mg,source)
SELECT p.id,${number(kcal)},${number(protein)},${number(carbs)},${number(fat)},${number(amount("269"))},${number(amount("291"))},${number(amount("307"))},${text(`USDA FoodData Central, ${record.dataType}, FDC ID ${record.fdcId}`)}
FROM products p WHERE p.name=${name}
ON CONFLICT (product_id) DO UPDATE SET calories=EXCLUDED.calories,protein_g=EXCLUDED.protein_g,carbs_g=EXCLUDED.carbs_g,fat_g=EXCLUDED.fat_g,sugar_g=EXCLUDED.sugar_g,fiber_g=EXCLUDED.fiber_g,sodium_mg=EXCLUDED.sodium_mg,source=EXCLUDED.source;`,
  );
}
const target = "backend/src/main/resources/db/usda/R__usda_catalog.sql";
writeFileSync(new URL(target, root), `${lines.join("\n")}\n`);
console.log(`Wrote ${foods.length} products to ${target}`);
